# TTS: wymowa imion (napis zostaje bez zmian)
SAY = [(r"\bZosia\b", "Zosha"), (r"\bNowak\b", "Novak"), (r"\bMalec\b", "Mahlets"), (r"\bKuba\b", "Kooba"),
       (r"\bIrena\b", "Ireena"), (r"\bJadzia\b", "Yadja"), (r"\bBasia\b", "Basha"), (r"\bWilk\b", "Vilk")]


def tts_text(s):
    for a, b in SAY:
        s = re.sub(a, b, s)
    return s.replace("...", ",").replace("…", ",")


def napis(s):
    """Tłumaczenie napisu w kadrze; nieznany zostaje (lista braków: film_en.py --braki)."""
    if s in TXT:
        return TXT[s]
    m = re.fullmatch(r"DZIEŃ (\d+)( · noc)?", s)
    if m:
        return f"DAY {m.group(1)}" + (" · NIGHT" if m.group(2) else "")
    return s
